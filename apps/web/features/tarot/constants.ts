export function getRandomLocalCards(count: number, locale: TarotLocale = "en"): TarotCardData[] {
  const deck = getTarotDeck(locale);
  const shuffled = [...deck].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
